/**
 * 「今日」字数口径的唯一真相源（UI 需求稿 UI-08 / 审查报告 PX-08）
 *
 * 同一个指标此前在三处各写各的，改一处口径要连改三处，漏一处就是「同一个数
 * 在三个面板显示成三种样子」：
 *
 * | 位置 | 原写法 | 问题 |
 * |---|---|---|
 * | 书架统计条卡 | 标签「今日新增（字）」+ 裸数字 | 单位写在标签里，与同排卡片（`12 部` / `48.2 万` / `5 天`）的「单位跟着数字」不一致 |
 * | 书架继续写作 Hero | 「今日 1,284 / 2,000 字」 | 用 `toLocaleString()` —— 跟着**系统区域设置**变（某些区域千分位不是逗号），与另外两处的 `formatThousands` 对不上 |
 * | 编辑器状态条 | 「今日 +120」 | 读的是**会话内**计数（`todayAdded`）而不是今日累计，于是刚打开编辑器时显示「今日 +0」，而紧挨着的进度条却按今日累计走 —— **同一条状态栏里两个「今日」**，也和书架的「今日新增」不是一个数 |
 *
 * 这里把口径定死，三处只允许引用本模块：
 *
 * - **术语**：`今日新增`（不用「今日 +N」「今日字数」等变体）
 * - **取值**：`usage_log` 的 `chapter_save` delta 净增聚合 + 会话内续加
 *   （即 store 的 `todayTotal`；书架与编辑器水合自同一个 `novel-usage-today`）
 * - **单位**：`字` 跟在数字后（不写进标签），与同排卡片保持一致
 * - **格式**：一律走 `formatThousands`（`@/shared/utils/format`），禁止 `toLocaleString`
 *
 * 净增口径的含义：删字扣回（`-500` 会把今日累计减回去）。取整后**负值展示为 0**
 * —— 「新增」不下穿零，这个截断在 `formatThousands` 里统一做，三处自动一致。
 *
 * PRD 开放问题「今日字数口径：净增 vs 保存累计」由此正式拍板为**净增**
 * （novel-editor-prd.md §10.3；现状即净增，无需迁移历史数据）。
 */

