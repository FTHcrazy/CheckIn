/**
 * 作品题材（genre）预设
 *
 * 定位：**可填可不填的辅助信息**，不是建书的必经步骤。
 * 它主要给 AI 用 —— 起名 / 润色时把题材当风格锚点（仙侠用字偏古雅、赛博朋克
 * 偏冷硬），没有它就只能按书名与已有要素弱推断。
 *
 * 为什么是「预设 + 允许自由填写」而不是枚举：
 * - 网络小说的分类本身一直在长（近几年才有「诸天无限」「规则怪谈」这类）；
 * - 作者写的是自己的书，用 CHECK 约束住分类，只会让他在列表里找不到想写的那个，
 *   然后被迫选一个错的 —— 错题材比无题材更糟（会把 AI 往反方向带）。
 *
 * 存库是中文自由文本（主进程 `normalizeGenre` 负责压空格 + 截断 30 字）。
 */

